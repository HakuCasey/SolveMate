import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { compile } from "json-schema-to-typescript";

const root = new URL("../", import.meta.url);
// Windows 检出或编辑器保存为 CRLF 时，换行差异不代表共享结构发生变化。
const normalizeLineEndings = (value) => value.replace(/\r\n/g, "\n");
const source = normalizeLineEndings(
  await readFile(
    new URL("packages/contracts/ai-metadata.schema.json", root),
    "utf8",
  ),
);
const schema = JSON.parse(source);
const generated = await compile(schema, "AiMetadataContract", {
  unreachableDefinitions: true,
  bannerComment:
    "/* Generated by npm run contracts:generate. Edit ai-metadata.schema.json. */",
  additionalProperties: false,
  // 数组长度由运行时 Schema 校验，生成普通数组，避免展开为大量元组联合。
  maxItems: 0,
  unknownAny: true,
});
const output = await format(generated, {
  parser: "typescript",
  endOfLine: "lf",
});
const files = [
  [
    "apps/local/src/solvemate_local/schemas/conversation-limits.json",
    normalizeLineEndings(
      await readFile(
        new URL("packages/contracts/conversation-limits.json", root),
        "utf8",
      ),
    ),
  ],
  [
    "apps/local/src/solvemate_local/schemas/robot-limits.json",
    normalizeLineEndings(
      await readFile(
        new URL("packages/contracts/robot-limits.json", root),
        "utf8",
      ),
    ),
  ],
  [
    "apps/local/src/solvemate_local/schemas/app-data.schema.json",
    normalizeLineEndings(
      await readFile(
        new URL("packages/contracts/app-data.schema.json", root),
        "utf8",
      ),
    ),
  ],
  ["packages/contracts/src/ai-metadata.generated.ts", output],
  ["apps/local/src/solvemate_local/schemas/ai-metadata.schema.json", source],
  [
    "apps/local/src/solvemate_local/schemas/ai-metadata-v2.schema.json",
    normalizeLineEndings(
      await readFile(
        new URL("packages/contracts/legacy/ai-metadata-v2.schema.json", root),
        "utf8",
      ),
    ),
  ],
];
for (const [path, value] of files) {
  const target = new URL(path, root);
  if (process.argv.includes("--check")) {
    if (
      normalizeLineEndings(await readFile(target, "utf8").catch(() => "")) !==
      value
    )
      throw new Error(`Generated AI contract is outdated: ${path}`);
  } else {
    await mkdir(fileURLToPath(new URL("./", target)), { recursive: true });
    await writeFile(target, value);
  }
}
console.log("AI metadata contracts verified.");
